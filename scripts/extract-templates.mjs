// Usage: node scripts/extract-templates.mjs [path-to/projects/dotnetreport-lib/src/lib]
// Pulls the Knockout markup + templates out of the Angular library into src/templates.generated.ts
import fs from 'fs';
import path from 'path';

const lib = process.argv[2] || '../dotnetreport-ng-lib/projects/dotnetreport-lib/src/lib';
const read = (...p) => fs.readFileSync(path.join(lib, ...p), 'utf8');

// Returns the content of the template literal passed to bypassSecurityTrustHtml inside `private <method>(`
function literal(ts, method) {
  const i = ts.indexOf(`private ${method}(`);
  const a = ts.indexOf('(`', ts.indexOf('bypassSecurityTrustHtml', i)) + 2;
  const raw = ts.slice(a, ts.indexOf('`);', a));
  if (i < 0 || raw.includes('${')) throw new Error(`cannot extract ${method}`);
  return new Function('return `' + raw + '`')(); // plain literal, no interpolation
}
const popover = (ts) => {
  const s = 'dateFormatPopoverContent: string = `';
  const a = ts.indexOf(s) + s.length;
  return new Function('return `' + ts.slice(a, ts.indexOf('`;', a)) + '`')();
};

const parts = { report: 'dotnetreport', dashboard: 'dotnetdashboard', setup: 'dotnetsetup' };
const out = {};
let dateFormatPopover = '';
for (const [key, name] of Object.entries(parts)) {
  const ts = read(name, `${name}.component.ts`);
  let html = read(name, `${name}.component.html`);
  const templates = literal(ts, 'renderKOTemplates');
  console.log(templates);
  if (key === 'dashboard') html = html.replace(/<div \[innerHTML\]="dashboardHtml"><\/div>/, () => literal(ts, 'renderKODashboardItems'));
  if (key === 'setup') html = html.replace(/<div \[innerHTML\]="dotNetSetupHtml"><\/div>/, () => literal(ts, 'renderKODotNetSetupItems'));
  html = html.replace(/<div \[innerHtml\]="reportTemplates"><\/div>/, () => templates);
  if (/\[innerHtml\]|\[innerHTML\]|\*ng/i.test(html)) throw new Error(`Angular syntax left in ${key}`);
  out[key] = html;
  dateFormatPopover ||= popover(ts);
}

const body =
  '// AUTO-GENERATED by scripts/extract-templates.mjs - do not edit\n' +
  Object.entries(out).map(([k, v]) => `export const ${k}Html = ${JSON.stringify(v)};\n`).join('') +
  `export const dateFormatPopover = ${JSON.stringify(dateFormatPopover)};\n`;
fs.writeFileSync(new URL('../src/templates.generated.ts', import.meta.url), body);
console.log('templates written:', Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.length])));
